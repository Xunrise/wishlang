/// The system prompt for a cycle: base rules plus the mode.
pub fn rules(lang: Lang, implement: bool) -> String {
    let (base, prototype, implement_rules) = match lang {
        Lang::Rust => (RULES, PROTOTYPE, IMPLEMENT),
        Lang::Java => (RULES_JAVA, PROTOTYPE_JAVA, IMPLEMENT_JAVA),
    };
    format!("{base}\n\n{}", if implement { implement_rules } else { prototype })
}

/// The tools Claude may run without asking.
fn allowed_tools(lang: Lang) -> &'static str {
    match lang {
        Lang::Rust => "Read,Edit,Write,Glob,Grep,Bash(cargo check:*),Bash(cargo add:*),Bash(cargo remove:*),Bash(cargo tree:*)",
        Lang::Java => "Read,Edit,Write,Glob,Grep,Bash(mvn -q compile:*),Bash(mvn dependency:tree:*)",
    }
}

/// The report's JSON schema; for a ticket cycle every change must name the problems it serves.
pub fn report_schema(ticket: bool) -> Value {
    let mut schema = json!({
        "type": "object",
        "properties": {
            "summary": {"type": "string", "description": "2-4 lines: what you built or changed and why"},
            "changes": {"type": "array", "description": "One entry per item you added, changed or removed", "items": {
                "type": "object",
                "properties": {
                    "item": {"type": "string", "description": "Item path, e.g. `Mode::Windowed`, `Window::open`, `impl Display for Mode`"},
                    "why": {"type": "string", "description": "1-2 concrete sentences: what in the user's code or lines led to this"}
                },
                "required": ["item", "why"]
            }},
            "decisions": {"type": "array", "items": {
                "type": "object",
                "properties": {
                    "kind": {"type": "string", "enum": ["dependency", "architecture"]},
                    "title": {"type": "string"},
                    "choice": {"type": "string"},
                    "alternatives": {"type": "array", "items": {"type": "string"}},
                    "why": {"type": "string"},
                    "crates": {"type": "array", "items": {"type": "string"}}
                },
                "required": ["kind", "title", "choice", "alternatives", "why", "crates"]
            }},
            "suggestions": {"type": "array", "items": {
                "type": "object",
                "properties": {
                    "file": {"type": "string"},
                    "reason": {"type": "string"},
                    "replace": {"type": "string"},
                    "with": {"type": "string"}
                },
                "required": ["file", "reason", "replace", "with"]
            }}
        },
        "required": ["summary", "changes", "decisions", "suggestions"]
    });
    if ticket {
        let change = &mut schema["properties"]["changes"]["items"];
        change["properties"]["problems"] = json!({"type": "array", "items": {"type": "string"}, "description": "Ids of the ticket's problems this item serves; [] if none"});
        change["required"] = json!(["item", "why", "problems"]);
    }
    schema
}

#[derive(Debug, Default, Deserialize)]
pub struct Report {
    pub summary: String,
    #[serde(default)]
    pub changes: Vec<ReportChange>,
    #[serde(default)]
    pub decisions: Vec<ReportDecision>,
    #[serde(default)]
    pub suggestions: Vec<ReportSuggestion>,
}

#[derive(Debug, Deserialize)]
pub struct ReportChange {
    pub item: String,
    pub why: String,
    #[serde(default)]
    pub problems: Vec<String>,
}

#[derive(Debug, Deserialize)]
pub struct ReportDecision {
    pub kind: String,
    pub title: String,
    pub choice: String,
    #[serde(default)]
    pub alternatives: Vec<String>,
    pub why: String,
    #[serde(default)]
    pub crates: Vec<String>,
}

#[derive(Debug, Deserialize)]
pub struct ReportSuggestion {
    pub file: String,
    pub reason: String,
    pub replace: String,
    pub with: String,
}

pub fn run(project: &Project, prompt: &str, rules: &str, ticket: bool, sink: &mut dyn Sink) -> Result<Report> {
    let exe = std::env::current_exe()?;
    let settings = json!({"hooks": {"PreToolUse": [{
        "matcher": "Edit|Write|MultiEdit|NotebookEdit|Bash",
        "hooks": [{"type": "command", "command": format!("'{}' hook", exe.display())}]
    }]}});

    let mut cmd = Command::new(std::env::var("WISH_CLAUDE").unwrap_or_else(|_| "claude".into()));
    cmd.current_dir(&project.root)
        .arg("-p")
        .args(["--output-format", "stream-json", "--verbose"])
        .args(["--json-schema", &report_schema(ticket).to_string()])
        .args(["--settings", &settings.to_string()])
        .args(["--append-system-prompt", rules])
        .args(["--allowedTools", allowed_tools(project.lang)]);
    if let Ok(model) = std::env::var("WISH_MODEL") {
        cmd.args(["--model", &model]);
    }
    let mut child = cmd
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("starting `claude` (is Claude Code installed and on PATH?)")?;
    child.stdin.take().unwrap().write_all(prompt.as_bytes())?;

    let mut stderr = child.stderr.take().unwrap();
    let err_thread = std::thread::spawn(move || {
        let mut err = String::new();
        let _ = std::io::Read::read_to_string(&mut stderr, &mut err);
        err
    });
    let stdout = child.stdout.take().unwrap();
    let mut result: Option<Value> = None;
    for line in BufReader::new(stdout).lines() {
        let line = line?;
        let Ok(v) = serde_json::from_str::<Value>(&line) else { continue };
        match v["type"].as_str() {
            Some("assistant") => {
                for c in v["message"]["content"].as_array().into_iter().flatten() {
                    match c["type"].as_str() {
                        Some("text") => sink.emit(Event::Says { text: c["text"].as_str().unwrap_or("").to_string() }),
                        Some("tool_use") => sink.emit(Event::Tool { name: c["name"].as_str().unwrap_or("?").to_string(), detail: tool_detail(project, &c["input"]) }),
                        _ => {}
                    }
                }
            }
            Some("user") => {
                for c in v["message"]["content"].as_array().into_iter().flatten() {
                    if c["type"] == "tool_result" && c["is_error"] == true {
                        let text = tool_result_text(&c["content"]);
                        if let Some(i) = text.find("wishlang:") {
                            sink.emit(Event::Blocked { reason: text[i + 9..].trim().lines().next().unwrap_or("").to_string() });
                        }
                    }
                }
            }
            Some("result") => result = Some(v),
            _ => {}
        }
    }
    let status = child.wait()?;
    let err = err_thread.join().unwrap_or_default();
    let Some(res) = result else {
        bail!("claude exited ({status}) without a result: {}", err.trim());
    };
    if res["is_error"] == true {
        bail!("claude reported an error: {}", res["result"].as_str().unwrap_or(&res["subtype"].to_string()));
    }
    if let Some(cost) = res["total_cost_usd"].as_f64() {
        let secs = res["duration_ms"].as_f64().unwrap_or(0.0) / 1000.0;
        sink.emit(Event::Status { msg: format!("claude finished in {secs:.0}s (${cost:.2})") });
    }
    let report_value = if res["structured_output"].is_object() {
        res["structured_output"].clone()
    } else {
        let text = res["result"].as_str().unwrap_or("");
        let start = text.find('{').unwrap_or(0);
        let end = text.rfind('}').map(|e| e + 1).unwrap_or(text.len());
        serde_json::from_str(&text[start..end]).unwrap_or(json!({"summary": text}))
    };
    Ok(serde_json::from_value(report_value).unwrap_or_default())
}

fn tool_detail(project: &Project, input: &Value) -> String {
    if let Some(f) = input["file_path"].as_str() {
        return project.rel(std::path::Path::new(f)).unwrap_or_else(|| f.to_string());
    }
    if let Some(c) = input["command"].as_str() {
        return c.to_string();
    }
    input["pattern"].as_str().unwrap_or("").to_string()
}

fn tool_result_text(c: &Value) -> String {
    match c {
        Value::String(s) => s.clone(),
        Value::Array(a) => a.iter().filter_map(|x| x["text"].as_str()).collect::<Vec<_>>().join("\n"),
        _ => String::new(),
    }
}
